/**
 * `:검색어` 매칭 — `:smi` 입력시 emoji + 이름 후보 반환
 * 영문·한글 별명 모두 지원. 결과는 제한 수만큼.
 */
export function emojiMatches(query: string, limit: number = 20): EmojiMatch[] {
  if (query.length === 0) return [];
  const q = query.toLowerCase();
  // 이름이 검색어로 시작하는 것 먼저, 같은 이모지는 한 번만
  const seen = new Set<string>();
  const hits = EMOJI_DATA.filter((e) => e.name.toLowerCase().includes(q) && !seen.has(e.emoji) && seen.add(e.emoji));
  const starts = (e: EmojiMatch) => (e.name.toLowerCase().startsWith(q) ? 0 : 1);
  return hits.sort((a, b) => starts(a) - starts(b)).slice(0, limit);
}
